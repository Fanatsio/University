from ultralytics import YOLO

if __name__ == "__main__":
    # Используем более крупную модель (s вместо n) для лучшей точности
    model = YOLO("yolov8s.pt")  # YOLOv8 small (вместо nano)

    model.train(
        data="data.yaml",
        epochs=50,  # Увеличили с 5 до 50 эпох
        imgsz=640,
        batch=16,  # Добавили размер батча
        patience=20,  # Early stopping если нет улучшений
        device=0,  # GPU (если доступен)
        
        # Аугментация данных для лучшей генерализации
        augment=True,
        hsv_h=0.015,  # Аугментация оттенка
        hsv_s=0.7,    # Аугментация насыщенности (важно для монеток)
        hsv_v=0.4,    # Аугментация яркости
        degrees=10,   # Поворот изображения
        translate=0.1,  # Смещение
        scale=0.5,    # Масштабирование
        flipud=0.5,   # Вертикальный флип
        fliplr=0.5,   # Горизонтальный флип
        perspective=0.0,  # Перспектива
        
        # Улучшение скорости обучения
        lr0=0.01,     # Начальная скорость обучения
        lrf=0.01,     # Финальная скорость обучения
        momentum=0.937,
        weight_decay=0.0005,
        
        save_period=5,  # Сохранять каждые 5 эпох
        verbose=True
    )

